import { OKLab } from './color';

/** De naam van de dichtstbijzijnde kleur in ALL, voor een hex als "#C8553D". Bij gelijke afstand wint de eerste. */
export function colorName(hex: string): string {
  const color = OKLab.fromHex(hex);
  let best = ENTRIES[0], bestDistance = Infinity;
  for (const entry of ENTRIES) {
    const d = distance(color, entry.lab);
    if (d < bestDistance) { bestDistance = d; best = entry; }
  }
  return best.name;
}

/** Het kwadraat van de rechte afstand in OKLab. */
function distance(a: OKLab, b: OKLab): number {
  const dl = a.l - b.l, da = a.a - b.a, db = a.b - b.b;
  return dl * dl + da * da + db * db;
}

